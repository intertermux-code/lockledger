"""Parser coverage for each supported lockfile shape."""

import json
from pathlib import Path

import pytest

from lockledger.parsers import FormatError, detect_format, parse_lockfile
from lockledger.parsers.npm import parse_npm_lock
from lockledger.parsers.pip import parse_requirements
from lockledger.parsers.uv import parse_uv_lock

from conftest import RECORDS, npm_lock


def as_records(records):
    return sorted((record.name, record.version) for record in records)


def test_npm_v3_packages_section(tmp_path):
    text = npm_lock(3, RECORDS)
    path = tmp_path / "package-lock.json"
    path.write_text(text)
    records = parse_lockfile(path)

    assert len(records) == len(RECORDS)
    assert ("left-pad", "1.3.0") in as_records(records)
    every = {record.name for record in records}
    assert "" not in every and "app" not in every  # the root entry is not a dependency
    one = next(record for record in records if record.name == "mime-types")
    assert one.resolved_url.endswith("mime-types-2.1.35.tgz")
    assert one.integrity == ""  # this lockfile records no subresource integrity
    assert {record.ecosystem for record in records} == {"npm"}


def test_npm_v3_handles_nested_and_scoped_and_workspace_entries():
    text = json.dumps(
        {
            "lockfileVersion": 3,
            "packages": {
                "": {"name": "root", "version": "1.0.0"},
                "node_modules/@scope/pkg": {
                    "version": "2.0.0",
                    "resolved": "https://registry.npmjs.org/@scope/pkg/-/pkg-2.0.0.tgz",
                    "integrity": "sha512-aaa",
                },
                "node_modules/a/node_modules/b": {"version": "0.2.0"},
                "packages/ui": {
                    "link": True,
                    "resolved": "file:../packages/ui",
                    "name": "ui",
                },
                "node_modules/vendored": {"version": "file:vendored.tgz", "resolved": "file:vendored.tgz"},
            },
        }
    )
    records = parse_npm_lock(text)
    assert as_records(records) == [("@scope/pkg", "2.0.0"), ("b", "0.2.0")]
    scoped = next(record for record in records if record.name == "@scope/pkg")
    assert scoped.integrity == "sha512-aaa"


def test_npm_v3_dependency_nested_under_a_scoped_parent():
    """The copy npm installs is the deepest one, so the leaf owns the version."""
    text = json.dumps(
        {
            "lockfileVersion": 3,
            "packages": {
                "": {"name": "root"},
                "node_modules/@babel/highlight": {"version": "7.0.0"},
                "node_modules/@babel/highlight/node_modules/semver": {"version": "5.7.0"},
                "node_modules/@x/main/node_modules/@y/leaf": {"version": "1.2.3"},
                "node_modules/debug/node_modules/ms": {"version": "2.0.0"},
            },
        }
    )
    assert as_records(parse_npm_lock(text)) == [
        ("@babel/highlight", "7.0.0"),
        ("@y/leaf", "1.2.3"),
        ("ms", "2.0.0"),
        ("semver", "5.7.0"),
    ]


def test_npm_v2_packages_and_legacy_dependencies_coexist():
    text = json.dumps(
        {
            "lockfileVersion": 2,
            "packages": {
                "": {"name": "root"},
                "node_modules/x": {"version": "1.0.0", "resolved": "https://r/x-1.0.0.tgz"},
            },
            "dependencies": {
                "x": {
                    "version": "1.0.0",
                    "resolved": "https://r/x-1.0.0.tgz",
                    "dependencies": {
                        "y": {"version": "0.9.0", "resolved": "https://r/y-0.9.0.tgz"}
                    },
                }
            },
        }
    )
    assert as_records(parse_npm_lock(text)) == [("x", "1.0.0"), ("y", "0.9.0")]


def test_npm_v1_legacy_tree_only():
    text = json.dumps(
        {
            "lockfileVersion": 1,
            "dependencies": {
                "left-pad": {
                    "version": "1.3.0",
                    "resolved": "https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz",
                    "integrity": "sha512-1",
                    "dependencies": {
                        "chalk": {
                            "version": "2.4.2",
                            "resolved": "https://registry.npmjs.org/chalk/-/chalk-2.4.2.tgz",
                        }
                    },
                },
                "local-thing": {"version": "1.0.0"},
            },
        }
    )
    records = parse_npm_lock(text)
    assert as_records(records) == [("chalk", "2.4.2"), ("left-pad", "1.3.0")]


def test_npm_rejects_other_json():
    with pytest.raises(ValueError, match="lockfileVersion"):
        parse_npm_lock(json.dumps({"name": "app", "version": "1.0.0"}))
    with pytest.raises(ValueError, match="invalid JSON"):
        parse_npm_lock("{not json")


def test_pip_freeze_and_requirements():
    text = """
    # generated by pip freeze
    Django==4.2.1
    requests[security]==2.31.0 ; python_version >= "3.8"
    urllib3==2.0.7  # comment
    colorama==0.4.6; sys_platform == "win32"
    """
    notes = []
    records = parse_requirements(text, notes)
    assert as_records(records) == [
        ("colorama", "0.4.6"),
        ("django", "4.2.1"),
        ("requests", "2.31.0"),
        ("urllib3", "2.0.7"),
    ]
    assert notes == []
    assert all(record.ecosystem == "pypi" for record in records)


def test_pip_hash_lines_attach_to_their_requirement():
    text = (
        "somepackage==1.2.3 \\\n"
        "    --hash=sha256:aaaa \\\n"
        "    --hash=sha256:bbbb\n"
        "other==0.1\n"
    )
    records = parse_requirements(text)
    by_name = {record.name: record for record in records}
    assert by_name["somepackage"].integrity == "sha256=aaaa;sha256=bbbb"
    assert by_name["other"].integrity == ""


def test_pip_reports_unpinned_and_editables():
    notes = []
    records = parse_requirements(
        "-e .\nflask>=2.0\nrich\nrequests @ https://example.com/requests-2.31.0-py3-none-any.whl\n",
        notes,
    )
    assert as_records(records) == [("requests", "unpinned")]
    assert records[0].resolved_url.endswith(".whl")
    assert any("editable" in note for note in notes)
    assert any("flask" in note for note in notes)
    assert any("rich" in note for note in notes)


def test_uv_lock_extracts_name_version_and_source(tmp_path):
    text = """
version = 1
requires-python = ">=3.11"

[[package]]
name = "Iniconfig"
version = "2.1.0"
source = { registry = "https://pypi.org/simple" }
sdist = { url = "https://files.pythonhosted.org/packages/source/i/iniconfig/iniconfig-2.1.0.tar.gz", hash = "sha256:aaa" }
wheels = [{ url = "https://files.pythonhosted.org/packages/py3/i/iniconfig/iniconfig-2.1.0-py3-none-any.whl", hash = "sha256:bbb" }]

[[package]]
name = "myapp"
version = "0.1.0"
source = { editable = "." }

[[package]]
name = "click"
version = "8.1.7"
source = { registry = "https://pypi.org/simple" }
wheels = [{ url = "https://files.pythonhosted.org/packages/py3/c/click/click-8.1.7-py3-none-any.whl", hash = "sha256:ccc" }]

[[package]]
name = "toolkit"
version = "0.2.0"
source = { git = "https://github.com/example/toolkit.git?rev=abcdef#abcdef" }
"""
    path = tmp_path / "uv.lock"
    path.write_text(text)
    notes = []
    records = parse_lockfile(path, notes=notes)

    assert as_records(records) == [
        ("click", "8.1.7"),
        ("iniconfig", "2.1.0"),
        ("toolkit", "0.2.0"),
    ]
    iniconfig = next(record for record in records if record.name == "iniconfig")
    assert iniconfig.resolved_url.endswith(".whl")
    assert iniconfig.integrity == "sha256=bbb"
    git_dep = next(record for record in records if record.name == "toolkit")
    assert git_dep.resolved_url.startswith("https://github.com")
    assert notes == ["skipped local package: myapp"]


def test_uv_lock_rejects_non_toml():
    with pytest.raises(ValueError, match="invalid TOML"):
        parse_uv_lock(b"[[package]\nname = broken")
    with pytest.raises(ValueError, match="no \\[\\[package\\]\\]"):
        parse_uv_lock(b'version = 1\n')


def test_uv_lock_needs_a_python_with_tomllib(monkeypatch):
    from lockledger.parsers import uv

    monkeypatch.setattr(uv, "tomllib", None)
    with pytest.raises(ValueError, match="Python 3.11"):
        parse_uv_lock(b'[[package]]\nname = "x"\nversion = "1.0.0"\n')


def test_format_detection():
    assert detect_format(Path("package-lock.json"), "{}") == "npm"
    assert detect_format(Path("npm-shrinkwrap.json"), "{}") == "npm"
    assert detect_format(Path("uv.lock"), "version = 1") == "uv"
    assert detect_format(Path("requirements.txt"), "a==1") == "pip"
    assert detect_format(Path("pipfreeze.txt"), "a==1") == "pip"
    assert detect_format(Path("mystery.json"), json.dumps({"lockfileVersion": 3})) == "npm"
    assert detect_format(Path("other.lock"), "[[package]]\nname = \"x\"") == "uv"
    with pytest.raises(FormatError, match="--format"):
        detect_format(Path("weird.lock"), "nonsense")


def test_unsupported_lockfile_with_explicit_format(tmp_path):
    path = tmp_path / "poetry.lock"
    path.write_text("[[package]]\nname = \"x\"\n")
    with pytest.raises(FormatError):
        parse_lockfile(path, "npm")


def test_lockfile_without_pinned_packages_is_an_error(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text("flask>=2.0\nrich\n")
    with pytest.raises(FormatError, match="no pinned packages"):
        parse_lockfile(path)
